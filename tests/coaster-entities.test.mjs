import { test } from 'node:test';
import assert from 'node:assert/strict';
import { harness } from './harness.mjs';
import { entityScenario, entityRates } from './entity-kit.mjs';

const settings=['settings','entities'].join('/');
test('Native entities isolate receipt policy and routing, consolidate exact USD evidence, and fence configuration, batches and provider authority',async()=>{
 const h=await harness({fxRates:entityRates});
 try {
  const f=await entityScenario(h),{team:t,ca,category,claims,submitted,report,batches}=f;
  assert.deepEqual(claims.map(c=>[c.entity_id,c.currency,c.total_minor,c.status]),[['primary','USD',10001,'approved'],[ca.id,'CAD',10002,'approved']]);
  assert.deepEqual(submitted[0].exceptions.map(e=>e.code),[]);
  assert.ok(submitted[1].exceptions.some(e=>e.code==='over-limit'));
  assert.equal(submitted[0].revisions[0].snapshot.entity.id,'primary');
  assert.equal(submitted[1].revisions[0].snapshot.entity.id,ca.id);
  assert.equal(submitted[1].revisions[0].snapshot.workflow.version,f.workflow.version);
  assert.equal(submitted[1].revisions[0].snapshot.items[0].allocations[0].account_code,'CA-6300');
  assert.deepEqual(submitted[1].events.find(e=>e.action==='expense-added').detail.currency,'CAD');
  assert.deepEqual(submitted[1].events.find(e=>e.action==='expense-added').detail.entity,ca.id);
  assert.equal(report.totalMinor,17503);
  assert.deepEqual(report.lines.map(l=>[l.currency,l.nativeMinor,l.amountMinor,l.fx_rate,l.fx_date,l.fx_source]),[['USD',10001,10001,'1','2026-10-02','native currency'],['CAD',10002,7502,'0.75','2026-10-02','ECB reference rates']]);
  assert.equal(report.lines.some(l=>l.claim===f.draft.id),false);
  assert.equal(JSON.stringify(report).includes('Private Canadian draft'),false);
  assert.deepEqual(await h.get(['spend','consolidated',report.id].join('/'),t.morgan),report);
  const regular=await h.get('spend?by=category&from=2026-10-01&to=2026-10-31',t.morgan);
  assert.equal(regular.totalMinor,10001);assert.equal(regular.currency,'USD');
  const state=await h.get('state',t.sam);
  assert.deepEqual(state.entities.map(e=>e.currency).sort(),['CAD','USD']);
  assert.ok(state.entities.every(e=>e.members.includes(f.employee)));
  const before=await h.db.prepare('SELECT COUNT(*) n FROM c_events').first();
  await h.post(settings,{name:'Refused',currency:'CAD',timezone:'America/Toronto'},t.sam,403);
  await h.post(`${settings}/${ca.id}/categories`,{id:f.us.categories[0].id,name:'Foreign',accountCode:'BAD',taxCode:'BAD'},h.owner,409);
  await h.post(`${settings}/${ca.id}/workflow`,{version:f.workflow.version,rules:[{label:'Foreign category',condition:{kind:'category',value:f.us.categories[0].id},stages:[[{kind:'manager'}]]}]},h.owner,400);
  await h.post(`${settings}/${ca.id}/policy`,{rules:[{kind:'blocked-category',category:f.us.categories[0].id}]},h.owner,400);
  assert.deepEqual(await h.db.prepare('SELECT COUNT(*) n FROM c_events').first(),before);
  const other=(await h.get('state',t.alex)).actor.email;
  await h.post('claims',{title:'Foreign member',entityId:ca.id},t.alex,403);
  let blocked=await f.make(ca.id,'Restricted shop','10.00',category.id);
  const unchanged=await h.get(`claims/${blocked.id}`,t.sam);
  await h.post(`claims/${blocked.id}/submit`,{version:blocked.version},t.sam,409);
  assert.deepEqual(await h.get(`claims/${blocked.id}`,t.sam),unchanged);
  const primary=await f.make('primary','Restricted shop','10.00',f.us.categories[0].id);
  const allowed=await h.post(`claims/${primary.id}/submit`,{version:primary.version},t.sam);
  assert.equal(allowed.status,'submitted');
  const another=await f.make('primary','Additional US visit','11.00',f.us.categories[0].id);
  let one=await h.post(`claims/${another.id}/submit`,{version:another.version},t.sam);
  one=await h.post(`claims/${one.id}/decision`,{version:one.version,revision:one.revision,decision:'approved',acknowledge:true},t.priya);
  let two=await f.make(ca.id,'Additional Canadian visit','12.00',category.id);
  two=await h.post(`claims/${two.id}/submit`,{version:two.version},t.sam);
  two=await h.post(`claims/${two.id}/decision`,{version:two.version,revision:two.revision,decision:'approved',acknowledge:true},t.priya);
  two=await h.post(`claims/${two.id}/decision`,{version:two.version,revision:two.revision,decision:'approved',acknowledge:true},t.morgan);
  const batchCount=await h.db.prepare('SELECT COUNT(*) n FROM c_batches').first();
  await h.post('batches',{claims:[one.id,two.id]},t.morgan,409);
  await h.post('batches',{claims:[claims[0].id]},t.morgan,409);
  assert.deepEqual(await h.db.prepare('SELECT COUNT(*) n FROM c_batches').first(),batchCount);
  assert.deepEqual(batches.map(b=>[b.entity_id,b.currency,b.total_minor]),[['primary','USD',10001],[ca.id,'CAD',10002]]);
  const outbound=h.outbound.length;
  await h.get(`batches/${batches[1].id}/payroll`,h.owner,409);
  await h.post(['accounting','qbo','connect'].join('/'),{entityId:ca.id},h.owner,409);
  assert.equal(h.outbound.length,outbound,'wrong-entity provider requests never reach the network');
  await h.get(['spend','consolidated',report.id].join('/'),t.sam,403);
  await h.post(`${settings}/${ca.id}/members`,{email:f.employee,active:false});
  const withdrawn=await h.get(`claims/${blocked.id}`,t.sam);
  await h.post(`claims/${blocked.id}/items`,{version:blocked.version,kind:'receipt',date:'2026-10-02',merchant:'New',amount:'9.00',category:category.id},t.sam,403);
  assert.deepEqual(await h.get(`claims/${blocked.id}`,t.sam),withdrawn);
  await h.post(`${settings}/${ca.id}/members`,{email:other,active:true});
  assert.ok((await h.get('state',t.alex)).entities.some(e=>e.id===ca.id));
  const key=await h.post('agent-keys',{label:'synthetic-coaster-entity-key'},t.alex);
  await h.post(['settings','members'].join('/'),{email:other,name:'Former entity member',employee:true,active:false});
  await h.post(['settings','members','erase'].join('/'),{email:other});
  assert.equal((await h.db.prepare('SELECT COUNT(*) n FROM c_entity_members WHERE email=?').bind(other).first()).n,0);
  await h.get('state',t.alex,401);
  const revoked=await h.send('/api/coaster/agent/claims',{title:'Refused erased member'},'',{authorization:'Bearer '+key.token});
  assert.equal(revoked.status,401);
  for(const batch of batches) {
   const reviewed=await h.post(`batches/${batch.id}/approve`,{version:batch.version,expectedTotal:batch.total_minor});
   await h.paid(batch.id,reviewed.version,{reference:'synthetic-coaster-external-payment',paidOn:'2026-10-15'});
  }
  await h.post(['settings','retention'].join('/'),{years:1});
  await (await h.mf.getWorker()).scheduled({scheduledTime:Date.now()+370*86400000,cron:'17 * * * *'});
  const expiry=(await h.get('retention')).proposal;
  assert.ok(expiry,'paid entity claims enter the existing retention proposal');
  assert.deepEqual(await h.get(['spend','consolidated',report.id].join('/')),report,'a proposal removes no report');
  await h.post(`retention/${expiry.id}/confirm`,{});
  await h.get(['spend','consolidated',report.id].join('/'),h.owner,404);

 }finally{await h.close();}
});
